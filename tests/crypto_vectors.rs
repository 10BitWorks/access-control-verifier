#[test]
fn test_rfc4493_aes_cmac_vectors() {
    // RFC 4493 AES-CMAC Test Vectors
    // K = 2b7e1516 28aed2a6 abf71588 09cf4f3c
    let k = hex::decode("2b7e151628aed2a6abf7158809cf4f3c").unwrap();

    // Subkey generation vectors not easily testable directly here, focus on message vectors

    // Message empty
    let m1: [u8; 0] = [];
    let t1 = hex::decode("bb1d6929e95937287fa37d129b756746").unwrap();
    assert_eq!(&aes_cmac(&k, &m1)[..], &t1[..]);

    // Message 16 bytes
    let m2 = hex::decode("6bc1bee22e409f96e93d7e117393172a").unwrap();
    let t2 = hex::decode("070a16b46b4d4144f79bdd9dd04a287c").unwrap();
    assert_eq!(&aes_cmac(&k, &m2)[..], &t2[..]);

    // RFC 4493 test vectors:
    // M = 6bc1bee22e409f96e93d7e117393172a ae2d8a571e03ac9c9eb76fac45af8e51 30c81c46a35ce411
    // Wait, the string "30c81c46a35ce411" is only 8 bytes. So 16+16+8 = 40 bytes.
    // Let me check my m3 hex string:
    // Message 40 bytes
    let m3 = hex::decode(
        "6bc1bee22e409f96e93d7e117393172aae2d8a571e03ac9c9eb76fac45af8e5130c81c46a35ce411",
    )
    .unwrap();
    let t3 = hex::decode("dfa66747de9ae63030ca32611497c827").unwrap();
    assert_eq!(&aes_cmac(&k, &m3)[..], &t3[..]);

    // Message 64 bytes
    let m3 = hex::decode("6bc1bee22e409f96e93d7e117393172aae2d8a571e03ac9c9eb76fac45af8e5130c81c46a35ce411e5fbc1191a0a52eff69f2445df4f9b17ad2b417be66c3710").unwrap();
    let t3 = hex::decode("51f0bebf7e3b9d92fc49741779363cfe").unwrap();
    assert_eq!(&aes_cmac(&k, &m3)[..], &t3[..]);
}

#[test]
fn test_golden_vectors_from_script() {
    // Master key: 000102030405060708090a0b0c0d0e0f
    let master = Key::from_hex("000102030405060708090a0b0c0d0e0f").unwrap();

    // Golden vectors generated by scripts/sun_golden.py via pylibsdm's own code
    // paths (generate_sdm_session_keys + cmac_input_from_uri + validate_cmac).
    // Wire format pinned there and in crypto.rs: mac_input =
    // "{UID:14 UPPERCASE hex}&c={CTR:06 UPPERCASE hex}&cmac=", e.g.
    // https://10bitworks.org/k?uid=046522CABC5D80&c=000001&cmac=...
    // SUN cmac is the 8-byte odd-byte truncation of the AES-CMAC over mac_input
    // with the SV2-derived session key (AN12196 secs. 3.3, 3.4.4.2).

    // Vector set 1
    let uid1 = Uid::from_hex("046522CABC5D80").unwrap();
    let tag_key1 = diversify(&master, &uid1);
    let expected_tag_key = hex::decode("71A4EC87107F7FC71B2220E23D8CE93A").unwrap();
    assert_eq!(&tag_key1.0[..], &expected_tag_key[..]);

    let expected: &[(u32, &str, &str)] = &[
        (1, "C30319AC9B924D5D42F1DB871821E65B", "4BE403BA3E9B7BD0"),
        (8, "08D4380C34F41ED6506C6362AA43B287", "C894C366C5802E34"),
        (11, "C371C486F40250C4B46F27ED2BF9D64C", "2EBFCD8D2474E800"),
        (255, "3048E917D855466160E73E37E4622C94", "30A08B95BAAD09A4"),
    ];
    for (counter, session, cmac) in expected {
        let counter1 = TapCounter::from_u32(*counter);
        assert_eq!(
            &session_mac_key(&tag_key1, &uid1, &counter1)[..],
            &hex::decode(session).unwrap()[..]
        );
        let cmac1 = cmac_for(&master, &uid1, &counter1);
        assert_eq!(&cmac1.0[..], &hex::decode(cmac).unwrap()[..]);
        assert!(verify_sun(&uid1, &counter1, &cmac1, &tag_key1).is_ok());
    }

    // Vector set 2
    let uid2 = Uid::from_hex("04112233445566").unwrap();
    let tag_key2 = diversify(&master, &uid2);
    let expected_tag_key2 = hex::decode("F7AEA5DCD43A919C6EFE1EB0F1222B1E").unwrap();
    assert_eq!(&tag_key2.0[..], &expected_tag_key2[..]);

    let expected2: &[(u32, &str, &str)] = &[
        (1, "9D48C8F60F9A236387E0A1F33B281746", "D3FB1FF0DC01ED43"),
        (8, "DC0E652032CC0D3B51FF2C6AE056DBD1", "8A4E1B1A46979F04"),
        (11, "BCF0C2940F8CBEDFACD529B3409E6AB3", "408A4C5B0FB4711F"),
        (255, "FDDB07B191979F2FB5F4A27EF3682A7C", "43CA550B8FE1C3C1"),
    ];
    for (counter, session, cmac) in expected2 {
        let counter2 = TapCounter::from_u32(*counter);
        assert_eq!(
            &session_mac_key(&tag_key2, &uid2, &counter2)[..],
            &hex::decode(session).unwrap()[..]
        );
        let cmac2 = cmac_for(&master, &uid2, &counter2);
        assert_eq!(&cmac2.0[..], &hex::decode(cmac).unwrap()[..]);
        assert!(verify_sun(&uid2, &counter2, &cmac2, &tag_key2).is_ok());
    }
}

#[test]
fn test_an12196_worked_example() {
    // NXP AN12196 worked examples, independent of pylibsdm. Pins the SV2
    // session-key derivation and the odd-index [1::2] truncation directly
    // against NXP's published numbers.

    // sec. 4.3 session-key example: KSDMFileRead = 5ACE7E50AB65D5D51FD5BF5A16B8205B,
    // UID 04C767F2066180, SDMReadCtr 010000 (LSB) -> value 1, SV2
    // 3CC30001008004C767F2066180010000 -> KSesSDMFileReadMAC 3A3E8110E05311F7A3FCF0D969BF2B48.
    let key1 = TagKey(
        hex::decode("5ACE7E50AB65D5D51FD5BF5A16B8205B")
            .unwrap()
            .try_into()
            .unwrap(),
    );
    let uid1 = Uid::from_hex("04C767F2066180").unwrap();
    assert_eq!(
        &session_mac_key(&key1, &uid1, &TapCounter::from_u32(1))[..],
        &hex::decode("3A3E8110E05311F7A3FCF0D969BF2B48").unwrap()[..]
    );

    // sec. 4.4.4.2.2: KeySDMFileReadMAC = 0000..00, UID 04958CAA5C5E80,
    // SDMReadCtr 080000 (LSB) -> value 8, SV2 3CC30001008004958CAA5C5E80080000
    //   -> KSesSDMFileReadMAC 3ED0920E5E6A0320D823D5987FEAFBB1
    // Step 15-16 + 10: MACt over the ASCII mirror slice
    //   "CEE9A53E3E463EF1F459635736738962&cmac=" -> ECC1E7F6C6C73BF6
    let tag_key = TagKey([0u8; 16]);
    let uid = Uid::from_hex("04958CAA5C5E80").unwrap();
    let counter = TapCounter::from_u32(8);
    let session = session_mac_key(&tag_key, &uid, &counter);
    assert_eq!(
        &session[..],
        &hex::decode("3ED0920E5E6A0320D823D5987FEAFBB1").unwrap()[..]
    );
    let mac = sun_mac(&session, b"CEE9A53E3E463EF1F459635736738962&cmac=");
    assert_eq!(&mac[..], &hex::decode("ECC1E7F6C6C73BF6").unwrap()[..]);
}

#[test]
fn test_wire_constructors() {
    assert_eq!(
        Uid::from_hex("046522cabc5d8").unwrap_err(),
        SunError::BadUid
    );
    assert_eq!(
        Uid::from_hex("046522cabc5d800").unwrap_err(),
        SunError::BadUid
    );
    assert_eq!(
        Uid::from_hex("invalidhexstrg").unwrap_err(),
        SunError::BadUid
    );
    assert!(Uid::from_hex("046522cabc5d80").is_ok());

    assert_eq!(
        TapCounter::from_hex("00000").unwrap_err(),
        SunError::BadCounter
    );
    assert_eq!(
        TapCounter::from_hex("0000001").unwrap_err(),
        SunError::BadCounter
    );
    assert_eq!(
        TapCounter::from_hex("nothex").unwrap_err(),
        SunError::BadCounter
    );
    assert!(TapCounter::from_hex("000001").is_ok());

    // Now 8-byte SUN cmacs (16 hex chars), not the old 32.
    assert_eq!(
        SunCmac::from_hex("4BE403BA3E9B7BD").unwrap_err(),
        SunError::BadCmac
    );
    assert_eq!(
        SunCmac::from_hex("4BE403BA3E9B7BD0F").unwrap_err(),
        SunError::BadCmac
    );
    assert_eq!(
        SunCmac::from_hex("invalidhexinvalidhexin").unwrap_err(),
        SunError::BadCmac
    );
    assert!(SunCmac::from_hex("4BE403BA3E9B7BD0").is_ok());
}

#[test]
fn test_tamper_detection() {
    // Golden cmac for uid 046522CABC5D80 / counter 1:
    // any single-bit flip anywhere in the 8-byte SUN cmac must be rejected.
    let master = Key::from_hex("000102030405060708090a0b0c0d0e0f").unwrap();
    let uid1 = Uid::from_hex("046522CABC5D80").unwrap();
    let counter1 = TapCounter::from_u32(1);
    let tag_key1 = diversify(&master, &uid1);

    let cmac1 = cmac_for(&master, &uid1, &counter1);
    assert!(verify_sun(&uid1, &counter1, &cmac1, &tag_key1).is_ok());

    #[allow(clippy::needless_range_loop)]
    for i in 0..8 {
        let mut tampered = cmac1.0;
        tampered[i] ^= 0x01;
        assert_eq!(
            verify_sun(&uid1, &counter1, &SunCmac(tampered), &tag_key1),
            Err(SunError::CmacMismatch)
        );
    }
}
#[test]
fn test_tap_counter_conversion() {
    let c = TapCounter::from_u32(1);
    assert_eq!(c.0, [0x00, 0x00, 0x01]);
    assert_eq!(c.to_u32(), 1);

    let c = TapCounter::from_u32(256);
    assert_eq!(c.0, [0x00, 0x01, 0x00]);
    assert_eq!(c.to_u32(), 256);

    let c = TapCounter::from_u32(0xFFFFFF);
    assert_eq!(c.0, [0xFF, 0xFF, 0xFF]);
    assert_eq!(c.to_u32(), 0xFFFFFF);
}
